#define ROR8(x)  (((x) >> 8) | ((x) << 24))
#define ROR16(x) (((x) >> 16) | ((x) << 16))
#define ROR24(x) (((x) >> 24) | ((x) << 8))

#define SUBWORD(x) \
	(((uint32_t)sbox[((x) >> 24) & 0xff] << 24) | \
	 ((uint32_t)sbox[((x) >> 16) & 0xff] << 16) | \
	 ((uint32_t)sbox[((x) >> 8) & 0xff] << 8) | \
	  (uint32_t)sbox[(x) & 0xff])

void
rtw_aes_set_key(struct rtw_aes_key *k, const uint8_t key[16])
{
	static const uint8_t rcon[10] = {
		0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
	};
	uint32_t *rk = k->rk, t;
	int i;

	for (i = 0; i < 4; i++)
		rk[i] = RTW_GET_BE32(key + 4 * i);
	for (i = 4; i < 44; i++) {
		t = rk[i - 1];
		if ((i & 3) == 0) {
			t = (t << 8) | (t >> 24);
			t = SUBWORD(t) ^ ((uint32_t)rcon[i / 4 - 1] << 24);
		}
		rk[i] = rk[i - 4] ^ t;
	}
}

void
rtw_aes_encrypt(const struct rtw_aes_key *k, const uint8_t in[16],
    uint8_t out[16])
{
	const uint32_t *rk = k->rk;
	uint32_t s0, s1, s2, s3, t0, t1, t2, t3;
	int r;

	s0 = RTW_GET_BE32(in) ^ rk[0];
	s1 = RTW_GET_BE32(in + 4) ^ rk[1];
	s2 = RTW_GET_BE32(in + 8) ^ rk[2];
	s3 = RTW_GET_BE32(in + 12) ^ rk[3];
	rk += 4;
	for (r = 1; r < 10; r++, rk += 4) {
		t0 = Te0[s0 >> 24] ^ ROR8(Te0[(s1 >> 16) & 0xff]) ^
		    ROR16(Te0[(s2 >> 8) & 0xff]) ^ ROR24(Te0[s3 & 0xff]) ^
		    rk[0];
		t1 = Te0[s1 >> 24] ^ ROR8(Te0[(s2 >> 16) & 0xff]) ^
		    ROR16(Te0[(s3 >> 8) & 0xff]) ^ ROR24(Te0[s0 & 0xff]) ^
		    rk[1];
		t2 = Te0[s2 >> 24] ^ ROR8(Te0[(s3 >> 16) & 0xff]) ^
		    ROR16(Te0[(s0 >> 8) & 0xff]) ^ ROR24(Te0[s1 & 0xff]) ^
		    rk[2];
		t3 = Te0[s3 >> 24] ^ ROR8(Te0[(s0 >> 16) & 0xff]) ^
		    ROR16(Te0[(s1 >> 8) & 0xff]) ^ ROR24(Te0[s2 & 0xff]) ^
		    rk[3];
		s0 = t0; s1 = t1; s2 = t2; s3 = t3;
	}
	t0 = (((uint32_t)sbox[s0 >> 24] << 24) |
	    ((uint32_t)sbox[(s1 >> 16) & 0xff] << 16) |
	    ((uint32_t)sbox[(s2 >> 8) & 0xff] << 8) |
	    (uint32_t)sbox[s3 & 0xff]) ^ rk[0];
	t1 = (((uint32_t)sbox[s1 >> 24] << 24) |
	    ((uint32_t)sbox[(s2 >> 16) & 0xff] << 16) |
	    ((uint32_t)sbox[(s3 >> 8) & 0xff] << 8) |
	    (uint32_t)sbox[s0 & 0xff]) ^ rk[1];
	t2 = (((uint32_t)sbox[s2 >> 24] << 24) |
	    ((uint32_t)sbox[(s3 >> 16) & 0xff] << 16) |
	    ((uint32_t)sbox[(s0 >> 8) & 0xff] << 8) |
	    (uint32_t)sbox[s1 & 0xff]) ^ rk[2];
	t3 = (((uint32_t)sbox[s3 >> 24] << 24) |
	    ((uint32_t)sbox[(s0 >> 16) & 0xff] << 16) |
	    ((uint32_t)sbox[(s1 >> 8) & 0xff] << 8) |
	    (uint32_t)sbox[s2 & 0xff]) ^ rk[3];
	RTW_PUT_BE32(out, t0);
	RTW_PUT_BE32(out + 4, t1);
	RTW_PUT_BE32(out + 8, t2);
	RTW_PUT_BE32(out + 12, t3);
}

static uint8_t
gmul(uint8_t a, uint8_t b)
{
	uint8_t r = 0;

	while (b) {
		if (b & 1)
			r ^= a;
		a = (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1b : 0));
		b >>= 1;
	}
	return r;
}

static void
add_round_key(uint8_t s[16], const uint32_t *rk)
{
	int i;

	for (i = 0; i < 4; i++) {
		s[4 * i] ^= (uint8_t)(rk[i] >> 24);
		s[4 * i + 1] ^= (uint8_t)(rk[i] >> 16);
		s[4 * i + 2] ^= (uint8_t)(rk[i] >> 8);
		s[4 * i + 3] ^= (uint8_t)rk[i];
	}
}

void
rtw_aes_decrypt(const struct rtw_aes_key *k, const uint8_t in[16],
    uint8_t out[16])
{
	uint8_t s[16], t[16];
	int r, c, i;

	memcpy(s, in, 16);
	add_round_key(s, k->rk + 40);
	for (r = 9; r >= 0; r--) {
		/* InvShiftRows: row i moves right by i columns. */
		for (c = 0; c < 4; c++)
			for (i = 0; i < 4; i++)
				t[4 * ((c + i) & 3) + i] = s[4 * c + i];
		for (i = 0; i < 16; i++)
			s[i] = inv_sbox[t[i]];
		add_round_key(s, k->rk + 4 * r);
		if (r == 0)
			break;
		for (c = 0; c < 4; c++) {
			uint8_t a0 = s[4 * c], a1 = s[4 * c + 1];
			uint8_t a2 = s[4 * c + 2], a3 = s[4 * c + 3];

			s[4 * c] = (uint8_t)(gmul(a0, 14) ^ gmul(a1, 11) ^
			    gmul(a2, 13) ^ gmul(a3, 9));
			s[4 * c + 1] = (uint8_t)(gmul(a0, 9) ^ gmul(a1, 14) ^
			    gmul(a2, 11) ^ gmul(a3, 13));
			s[4 * c + 2] = (uint8_t)(gmul(a0, 13) ^ gmul(a1, 9) ^
			    gmul(a2, 14) ^ gmul(a3, 11));
			s[4 * c + 3] = (uint8_t)(gmul(a0, 11) ^ gmul(a1, 13) ^
			    gmul(a2, 9) ^ gmul(a3, 14));
		}
	}
	memcpy(out, s, 16);
}

int
rtw_aes_unwrap(const struct rtw_aes_key *kek, const uint8_t *in, size_t inlen,
    uint8_t *out)
{
	uint8_t a[8], b[16];
	size_t n, i;
	int j, x;

	if (inlen < 16 || (inlen & 7) != 0)
		return -1;
	n = inlen / 8 - 1;
	memcpy(a, in, 8);
	memmove(out, in + 8, n * 8);
	for (j = 5; j >= 0; j--) {
		for (i = n; i >= 1; i--) {
			uint32_t t = (uint32_t)(n * (size_t)j + i);

			memcpy(b, a, 8);
			b[7] ^= (uint8_t)t;
			b[6] ^= (uint8_t)(t >> 8);
			b[5] ^= (uint8_t)(t >> 16);
			b[4] ^= (uint8_t)(t >> 24);
			memcpy(b + 8, out + (i - 1) * 8, 8);
			rtw_aes_decrypt(kek, b, b);
			memcpy(a, b, 8);
			memcpy(out + (i - 1) * 8, b + 8, 8);
		}
	}
	x = 0;
	for (i = 0; i < 8; i++)
		x |= a[i] ^ 0xa6;
	return x ? -1 : 0;
}

/*
 * CCM (RFC 3610) with M = 8 and L = 2.  The CBC-MAC and the counter mode
 * keystream are computed in one pass over the data.
 */
static void
ccm_start(const struct rtw_aes_key *k, const uint8_t *nonce,
    const uint8_t *aad, size_t aadlen, size_t len, uint8_t x[16],
    uint8_t ctr[16])
{
	uint8_t b[16];
	size_t i, n;

	/* B0: flags (Adata, M, L), nonce, message length. */
	b[0] = (uint8_t)((aadlen ? 0x40 : 0) | (((RTW_CCM_MIC_LEN - 2) / 2) << 3) |
	    1);
	memcpy(b + 1, nonce, RTW_CCM_NONCE_LEN);
	b[14] = (uint8_t)(len >> 8);
	b[15] = (uint8_t)len;
	rtw_aes_encrypt(k, b, x);

	if (aadlen) {
		/* Two byte length prefix, then the AAD, zero padded. */
		x[0] ^= (uint8_t)(aadlen >> 8);
		x[1] ^= (uint8_t)aadlen;
		i = 2;
		while (aadlen > 0) {
			n = 16 - i;
			if (n > aadlen)
				n = aadlen;
			while (n--) {
				x[i++] ^= *aad++;
				aadlen--;
			}
			rtw_aes_encrypt(k, x, x);
			i = 0;
		}
	}

	ctr[0] = 1;	/* flags: L - 1 */
	memcpy(ctr + 1, nonce, RTW_CCM_NONCE_LEN);
	ctr[14] = ctr[15] = 0;
}

static void
ccm_ctr_block(const struct rtw_aes_key *k, uint8_t ctr[16], unsigned i,
    uint8_t s[16])
{
	ctr[14] = (uint8_t)(i >> 8);
	ctr[15] = (uint8_t)i;
	rtw_aes_encrypt(k, ctr, s);
}

void
rtw_ccm_encrypt(const struct rtw_aes_key *k,
    const uint8_t nonce[RTW_CCM_NONCE_LEN], const uint8_t *aad, size_t aadlen,
    uint8_t *data, size_t len, uint8_t mic[RTW_CCM_MIC_LEN])
{
	uint8_t x[16], ctr[16], s[16];
	unsigned blk = 1;
	size_t i, n;

	ccm_start(k, nonce, aad, aadlen, len, x, ctr);
	while (len > 0) {
		n = (len < 16) ? len : 16;
		ccm_ctr_block(k, ctr, blk++, s);
		for (i = 0; i < n; i++) {
			x[i] ^= data[i];
			data[i] ^= s[i];
		}
		rtw_aes_encrypt(k, x, x);
		data += n; len -= n;
	}
	ccm_ctr_block(k, ctr, 0, s);
	for (i = 0; i < RTW_CCM_MIC_LEN; i++)
		mic[i] = (uint8_t)(x[i] ^ s[i]);
}

int
rtw_ccm_decrypt(const struct rtw_aes_key *k,
    const uint8_t nonce[RTW_CCM_NONCE_LEN], const uint8_t *aad, size_t aadlen,
    uint8_t *data, size_t len, const uint8_t mic[RTW_CCM_MIC_LEN])
{
	uint8_t x[16], ctr[16], s[16], t[RTW_CCM_MIC_LEN];
	unsigned blk = 1;
	size_t i, n;

	ccm_start(k, nonce, aad, aadlen, len, x, ctr);
	while (len > 0) {
		n = (len < 16) ? len : 16;
		ccm_ctr_block(k, ctr, blk++, s);
		for (i = 0; i < n; i++) {
			data[i] ^= s[i];
			x[i] ^= data[i];
		}
		rtw_aes_encrypt(k, x, x);
		data += n; len -= n;
	}
	ccm_ctr_block(k, ctr, 0, s);
	for (i = 0; i < RTW_CCM_MIC_LEN; i++)
		t[i] = (uint8_t)(x[i] ^ s[i]);
	return rtw_memeq_ct(t, mic, RTW_CCM_MIC_LEN) ? 0 : -1;
}
